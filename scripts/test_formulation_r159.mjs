assert.equal(g.exportRows(g.colostrum,state).slice(1).filter(r=>r[10].includes('L-159')).length,1);
assert(ctx.PMSVTestingPlan.entries(g.colostrum,date,state).some(r=>r.area===g.area&&r.notes.includes('R-159')));
