/* PMSV source-edition numerical comparison only. Not regulatory or lot approval.
   Requires the reviewed registry generated by cereal_review.py. No default units,
   analytical bases, subtype, conversion, method equivalence or product approval. */
(function(root){'use strict';
const own=(o,k)=>Object.prototype.hasOwnProperty.call(o,k);
const plain=o=>o!==null&&typeof o==='object'&&!Array.isArray(o);
const same=(a,b)=>typeof a===typeof b&&a===b;
function make(registry){
 if(!plain(registry)||registry.batch_id!=='CEREALS_R3_2026_11_02'||!Array.isArray(registry.rules)||!Array.isArray(registry.products))throw new TypeError('Reviewed cereal registry required');
 // Clone: callers cannot mutate the input after construction and change limits.
 const reg=JSON.parse(JSON.stringify(registry));
 const products=new Map(reg.products.map(p=>[p.id,p])),rules=new Map(reg.rules.map(r=>[r.id,r]));
 if(products.size!==reg.products.length||rules.size!==reg.rules.length)throw new Error('Duplicate registry keys');
 const domains={};
 for(const r of reg.rules){
  const d=domains[r.standard_key]||(domains[r.standard_key]={});
  for(const [k,v] of Object.entries(r.when||{})){
   const a=d[k]||(d[k]=[]);for(const q of typeof v==='boolean'?[false,true]:[v])if(!a.some(x=>same(x,q)))a.push(q);
  }
 }
 // Arrowroot is identity-only here; tapioca/palm numeric rows do not apply to it.
 domains['2.4.14'].starchy_food_type.push('arrowroot');
 function result(status,extra){return Object.assign({status,product_approved:false,current_law_verified:false,commercial_release_authorized:false,scope:'One source-edition requirement only; not complete compliance'},extra||{});}
 function evaluate(productId,ruleId,measurement,context={}){
  const p=products.get(productId);if(!p)return result('PRODUCT_NOT_REVIEWED');
  const r=rules.get(ruleId);if(!r||r.standard_key!==p.new_key)return result('RULE_NOT_IN_PRODUCT_STANDARD');
  if(!plain(context))return result('CONTEXT_INVALID');
  const d=domains[p.new_key]||{},fixed=p.fixed_context||{},choices=p.context_choices||{};
  for(const [k,v] of Object.entries(context)){
   if(!own(d,k)||!d[k].some(x=>same(x,v)))return result('CONTEXT_INVALID',{field:k});
   if(own(fixed,k)&&!same(v,fixed[k]))return result('CONTEXT_CONFLICT',{field:k});
   if(own(choices,k)&&!choices[k].some(x=>same(x,v)))return result('CONTEXT_OUTSIDE_CATALOGUE_IDENTITY',{field:k});
  }
  const c=Object.assign({},context,fixed);
  // A known subtype mismatch is determinative. A missing conditional key alone is not.
  for(const [k,v] of Object.entries(r.when||{}))if(own(c,k)&&!same(c[k],v))return result('NOT_APPLICABLE_TO_SELECTED_CONTEXT');
  const missing=Object.keys(r.when||{}).filter(k=>!own(c,k));if(missing.length)return result('CONTEXT_REQUIRED',{fields:missing});
  if(r.interpretation_status||r.source_question)return result('SOURCE_CLARIFICATION_REQUIRED',{reason:r.source_question});
  if(!r.automatic_comparison_allowed)return result('MANUAL_REVIEW_REQUIRED',{reason:'Qualitative/compound requirement or unspecified source basis'});
  if(!plain(measurement)||typeof measurement.value!=='number'||!Number.isFinite(measurement.value))return result('MEASUREMENT_REQUIRED');
  if(measurement.unit!==r.unit)return result('UNIT_MISMATCH',{expected:r.unit});
  if(measurement.basis!==r.analytical_basis)return result('BASIS_MISMATCH',{expected:r.analytical_basis});
  const x=measurement.value;if(x<0)return result('MEASUREMENT_INVALID');
  if((r.unit==='%'||r.unit==='g/100 g')&&x>100)return result('MEASUREMENT_INVALID');
  let ok;switch(r.operator){
   case '<=':ok=x<=r.value;break;case '>=':ok=x>=r.value;break;
   case '<':ok=x<r.value;break;case '>':ok=x>r.value;break;
   case '=':ok=x===r.value;break;case 'range':ok=x>=r.min&&x<=r.max;break;
   case 'open_range':ok=x>r.min&&x<r.max;break;default:return result('MANUAL_REVIEW_REQUIRED');
  }
  return result(ok?'SATISFIES_THIS_NUMERIC_LIMIT':'OUTSIDE_THIS_NUMERIC_LIMIT',{rule_id:r.id,source_clause:r.source_clause,source_pdf_pages:r.source_pdf_pages});
 }
 return Object.freeze({evaluate});
}
const api=Object.freeze({create:make});if(typeof module==='object'&&module.exports)module.exports=api;root.PMSVCerealSourceGuard=api;
})(typeof globalThis==='object'?globalThis:this);
