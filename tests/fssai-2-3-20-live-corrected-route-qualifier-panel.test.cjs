"use strict";
const {test}=require("node:test"),assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.resolve(__dirname,".."),prefix="fssai-product-helper-preview-01/";
const read=f=>JSON.parse(fs.readFileSync(path.join(root,prefix+"data/"+f),"utf8"));
const p=read("standard-search-index-v1.json").products.find(x=>x.id==="06-06-3-fruit-vegetable-cereal-flakes");
const m=read("rules/contaminants-v9-unresolved-264-review-v1.json");
const record=m.records.find(x=>x.catalog_id===p.id);
const html=fs.readFileSync(path.join(root,prefix+"index.html"),"utf8");
const a=html.indexOf("function pendingContaminantReviewNotice(p){"),b=html.indexOf("function renderProductContaminants(){",a);
const ctx=vm.createContext({contaminantsPendingReviewDb:m,esc:s=>String(s).replaceAll("&","&amp;").replaceAll("<","&lt;").replaceAll(">","&gt;")});
vm.runInContext(html.slice(a,b),ctx);
const show=x=>vm.runInContext("pendingContaminantReviewNotice("+JSON.stringify(x)+")",ctx);
test("Flakes route correction shows exact FSSAI Chapter 2.3 standard and four current identity-bound reviews",()=>{
 assert.equal(p.fssr,"2.3.20");assert.equal(record.fssr,"2.3.20");assert.equal(record.regulatory_family,"2.3");
 assert.equal(record.next_family_subtype_review_2026_10_10.fssr,p.fssr);
 assert.equal(record.precision_applicability_review_2026_10_10.fssr,p.fssr);
 assert.equal(record.exact_subtype_transfer_safeguard_2026_10_11.catalogue_fssr,p.fssr);
 const x=show(p);assert.match(x,/FSSAI 2.3.20 route corrected/);
 assert.match(x,/product quality only/);
 assert.match(x,/five required product\/analytical qualifiers/);
 assert.match(x,/11 October exact subtype transfer safeguard/);
 assert.match(x,/Exact product identity and matrix gates/);
 assert.match(x,/Detailed 2.3 food identity\/recipe review/);
 assert.match(x,/Contaminant evidence remains unresolved/);
 assert.doesNotMatch(x,/FSSAI named-standard routing discrepancy — review required/);
 assert.doesNotMatch(x,/Regulatory review record identity mismatch/);
 assert.match(x,/No numeric CTR finished-product limit auto-applied/);
 assert.doesNotMatch(show({...p,fssr:"2.4.35"}),/FSSAI 2.3.20 route corrected/);
 assert.equal(record.auto_apply_numeric_limit,false);
 assert.equal(record.unconditional_compliance_pass,false);
});
